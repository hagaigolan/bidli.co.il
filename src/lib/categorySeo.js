export const CATEGORY_HEADINGS = {
  "אלקטרוניקה": "מכרזי אלקטרוניקה",
  "עיצוב הבית": "מכרזי רהיטים",
  "יין ואלכוהול": "מכרזי יין",
  "שעונים": "מכרזי שעונים",
  "תכשיטים": "מכרזי תכשיטים",
  "אופנה": "מכרזי אופנה",
};

export function categoryHeading(name) {
  return CATEGORY_HEADINGS[name] || `מכרזי ${name}`;
}