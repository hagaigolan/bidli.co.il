// התאמת מיקום טקסטואלי לקואורדינטות. מחזיר { name, lat, lng } או null.
export function lookupCityCoords(location) {
  if (!location) return null;
  const clean = String(location).replace(/["״'`]/g, "").trim();
  if (!clean) return null;
  // הסרת קידומות אזוריות נפוצות
  const stripped = clean.replace(/^(אזור|מחוז|סביבות)\s+/, "");
  for (const [name, coords] of Object.entries(CITY_COORDS)) {
    if (clean.includes(name) || stripped === name) {
      return { name, lat: coords[0], lng: coords[1] };
    }
  }
  return null;
}