// נירמול: הסרת גרשיים, רווחים, מקפים וסימני פיסוק — כדי ש"רמת-גן" ו"רמת גן" יתאמו
function normalize(text) {
  return String(text)
    .replace(/["״'`׳]/g, "")
    .replace(/[\s\-–—.,;:()/\\]/g, "")
    .replace(/^(אזור|מחוז|סביבות|נפת)/, "");
}

// ממוין מהשם הארוך לקצר — התאמה מדויקת יותר כשיש כמה שמות חופפים
const ENTRIES = Object.entries(CITY_COORDS)
  .map(([name, coords]) => ({ name, key: normalize(name), coords }))
  .sort((a, b) => b.key.length - a.key.length);

// התאמת מיקום טקסטואלי לקואורדינטות. מחזיר { name, lat, lng } או null.
export function lookupCityCoords(location) {
  if (!location) return null;
  const clean = normalize(location);
  if (!clean) return null;
  const hit = ENTRIES.find(e => e.key.length > 2 && clean.includes(e.key));
  if (!hit) return null;
  return { name: hit.name, lat: hit.coords[0], lng: hit.coords[1] };
}