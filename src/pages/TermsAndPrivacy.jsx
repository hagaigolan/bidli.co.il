function Section({ section }) {
  const [open, setOpen] = useState(false);
  return (
    <div className="border border-gray-100 rounded-2xl overflow-hidden mb-3">
      <button
        onClick={() => setOpen(o => !o)}
        className="w-full flex items-center justify-between px-5 py-4 text-right hover:bg-gray-50 transition-colors"
        dir="rtl"
      >
        <span className="font-bold text-gray-800 text-sm leading-snug">{section.title}</span>
        {open
          ? <ChevronUp className="h-4 w-4 text-gray-400 flex-shrink-0 mr-3" />
          : <ChevronDown className="h-4 w-4 text-gray-400 flex-shrink-0 mr-3" />}
      </button>
      {open && (
        <div className="px-5 pb-5 border-t border-gray-50" dir="rtl">
          <p className="text-sm text-gray-600 leading-relaxed whitespace-pre-line pt-4">{section.content}</p>
        </div>
      )}
    </div>
  );
}

